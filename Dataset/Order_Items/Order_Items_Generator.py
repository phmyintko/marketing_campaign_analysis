from faker import Faker
import pandas as pd
import random

def order_items_generator():

    fake = Faker('en_TH')
    SEED = 92
    random.seed(SEED)
    fake.seed_instance(SEED)

    ### import related entitles
    order_df = pd.read_csv('Dataset/Order/Order_Data.csv',
        parse_dates=['Order_Date', 'Created_At']
        ).rename(columns={'Created_At': 'Order_Created_At'})
    product_df = pd.read_csv('Dataset/Product/Product_Data.csv',
        parse_dates=['Created_At']
        ).rename(columns={'Created_At': 'Product_Created_At'})
    product_category_df = pd.read_csv('Dataset/Product_Category/Product_Category_Data.csv')
    product_subcategory_df = pd.read_csv('Dataset/Product_Sub_Category/Product_Sub_Category_Data.csv')

    ### rules to generate product orders, product names are generated by sub category + category + color + size. color will be generated by randomly

    ## category 
    category_weight = {
        'Mattress': 0.46,
        'Bedsheet': 0.24,
        'Pillow': 0.16,
        'Bolster': 0.10,
        'Blanket': 0.04
    }

    ## sub category
    subcategory_weight = {
        'Mattress' : {
            'Foam': 0.15,
            'Spring': 0.50,
            'Pocket Spring': 0.35
        },
        'Bedsheet' : {
            'Cotton': 0.65,
            'Polyester': 0.25,
            'Linen': 0.10
        },
        'Pillow' : {
            'Cotton': 0.10,
            'Feather': 0.30,
            'Polyester': 0.60
        },
        'Bolster' : {
            'Cotton': 0.20,
            'Feather': 0.05,
            'Polyester': 0.75
        },
        'Blanket' : {
            'Cotton': 0.35,
            'Flannel': 0.15,
            'Fleece': 0.50
        }
    }
    
    ## size weight
    size_weight = {
        'Mattress': {
            'Foam': {'Single': 0.26, 'Queen': 0.40, 'King': 0.34},
            'Spring': {'Single': 0.20, 'Queen': 0.42, 'King': 0.38},
            'Pocket Spring': {'Single': 0.10, 'Queen': 0.36, 'King': 0.54}
        },
        'Bedsheet': {
            'Cotton': {'Single': 0.35, 'Queen': 0.25, 'King': 0.40},
            'Polyester': {'Single': 0.35, 'Queen': 0.25, 'King': 0.40},
            'Linen': {'Single': 0.35, 'Queen': 0.25, 'King': 0.40}
        },
        'Pillow': {
            'Cotton': {'One Size': 1.0}, 
            'Feather': {'One Size': 1.0}, 
            'Polyester': {'One Size': 1.0}
        },
        'Bolster': {
            'Cotton': {'One Size': 1.0}, 
            'Feather': {'One Size': 1.0}, 
            'Polyester': {'One Size': 1.0}
        },
            'Blanket': {
            'Cotton': {'Single': 0.20, 'Queen': 0.35, 'King': 0.45},
            'Flannel': {'Single': 0.20, 'Queen': 0.35, 'King': 0.45},
            'Fleece': {'Single': 0.20, 'Queen': 0.35, 'King': 0.45}
        }
    }

    ## quantity weight
    quantity_weight = {
        'One_Time':   {'qty': [1, 2, 3, 4], 'weights': [0.85, 0.10, 0.04, 0.01]},
        'Repeat':     {'qty': [1, 2, 3, 4], 'weights': [0.60, 0.25, 0.10, 0.05]},
        'Commercial': {'qty': [1, 2, 3, 4], 'weights': [0.10, 0.20, 0.40, 0.30]}
    }

    # join product, product_subcategory and product category in order to filter product by category, subcategory and size
    join_df = (
    product_df
    .merge(
        product_subcategory_df[
            ['Sub_Category_ID', 'Sub_Category_Name', 'Category_ID']
        ],
        on='Sub_Category_ID',
        how='left'
    )
    .merge(
        product_category_df[
            ['Category_ID', 'Category_Name']
        ],
        on='Category_ID',
        how='left'
    )
    )

    order_items_record = []

    ### loop each order to get order product data
    for orders in order_df.itertuples(index=False):

        ## random choices for category, sub category and size
        category = random.choices(list(category_weight.keys()), 
            weights=list(category_weight.values()))[0]
        
        subcat = subcategory_weight[category]
        subcategory = random.choices(
            list(subcat.keys()),
            weights=list(subcat.values()))[0]

        p_size = size_weight[category][subcategory]
        size = random.choices(
            list(p_size.keys()),
            weights=list(p_size.values()))[0]
        
        # filter matching product from product entity
        order_product = product_df[
            (join_df['Category_Name'] == category)
            &
            (join_df['Sub_Category_Name'] == subcategory)
            &
            (join_df['Size'] == size)
            ]
    
        ## fill data in the filtered row
        selected_product = order_product.sample(1).iloc[0]
        order_items_id = 'ORIT_' + fake.unique.uuid4()[:6]
        order_id = orders.Order_ID
        product_id = selected_product['Product_ID']

        # generate quantity
        cust_type = orders.Customer_Type
        type_rule = quantity_weight[cust_type]
        quantity = random.choices(type_rule['qty'], weights = type_rule['weights'])[0]

        unit_price = selected_product['Price']
        
        ## calculate total amount
        total_amt = unit_price * quantity

        # append results
        order_items_record.append({
            'Order_Items_ID': order_items_id,
            'Order_ID': order_id,
            'Product_ID': product_id,
            'Quantity': quantity,
            'Unit_Price': unit_price,
            'Total_Amount': total_amt
        })
    order_items_df = pd.DataFrame(order_items_record)
    return order_items_df

df = order_items_generator()
df.to_csv('Dataset/Order_Items/Order_Items_Data.csv')